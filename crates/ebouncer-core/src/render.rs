//! 账单渲染：Invoice → 打印级 HTML →（本机 Chrome/Edge 无头）PDF。
//! 水印只用于演示/截图（`--watermark`）；正式账单默认无水印，页脚保留来源与指纹。
//! 无浏览器时降级：HTML 即交付物，命令行给出提示——PDF 只是糖，数据才是产品。

use crate::bill::{Invoice, group_digits, tier_label, unit_basis};
use chrono::DateTime;
use std::path::{Path, PathBuf};
use std::process::Command;

fn esc(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// 账单周期只显示日期；解析失败时原样返回。
fn fmt_date(ts: &str) -> String {
    DateTime::parse_from_rfc3339(ts)
        .map(|d| d.format("%Y-%m-%d").to_string())
        .unwrap_or_else(|_| ts.to_string())
}

/// 生成时间去掉纳秒/偏移，统一显示 UTC。
fn fmt_datetime(ts: &str) -> String {
    DateTime::parse_from_rfc3339(ts)
        .map(|d| d.format("%Y-%m-%d %H:%M UTC").to_string())
        .unwrap_or_else(|_| ts.to_string())
}

fn currency_symbol(currency: &str) -> &'static str {
    match currency {
        "CNY" => "¥",
        "USD" => "$",
        _ => "",
    }
}

/// 账单编号：INV-YYYYMMDD-<账本指纹前 8 位>。无账本指纹时用占位符。
fn invoice_no(inv: &Invoice) -> String {
    let date = DateTime::parse_from_rfc3339(&inv.generated_at)
        .map(|d| d.format("%Y%m%d").to_string())
        .unwrap_or_else(|_| "00000000".to_string());
    let tail = inv
        .data_basis
        .as_deref()
        .map(|b| b.chars().take(8).collect::<String>().to_uppercase())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "--------".to_string());
    format!("INV-{date}-{tail}")
}

/// 平铺水印 SVG（data URI，ASCII 文本避免编码问题）。
/// 注意：这是**声明片段**，会被插进 `body{...}` 规则内部，不得再带选择器外壳。
const WATERMARK_CSS: &str = "background-image:url(\"data:image/svg+xml;utf8,<svg xmlns='http://www.w3.org/2000/svg' width='420' height='260'><text x='20' y='140' transform='rotate(-28 210 130)' font-family='sans-serif' font-size='26' fill='black' fill-opacity='0.07'>Generated by eBouncer - ebouncer.dev</text></svg>\");background-repeat:repeat";

pub fn invoice_html(inv: &Invoice) -> String {
    let wm = if inv.watermark {
        WATERMARK_CSS.to_string()
    } else {
        String::new()
    };
    let sym = currency_symbol(&inv.currency);
    let mut rows = String::new();
    for i in &inv.items {
        let note = i
            .note
            .as_deref()
            .map(|n| format!("<div class=note>{}</div>", esc(n)))
            .unwrap_or_default();
        rows.push_str(&format!(
            "<tr><td>{}</td><td>{}{}</td><td>{}</td><td>{}</td><td class=n>{}</td><td class=n>{:.4}</td><td class=n>{}{:.4}</td></tr>",
            esc(&i.tool),
            esc(&i.category),
            note,
            unit_basis(&i.category),
            tier_label(&i.price_source),
            group_digits(i.qty),
            i.unit_price_per_k_or_mtok,
            sym,
            i.amount
        ));
    }
    let no = invoice_no(inv);
    // 成本账单不含任何加成；markup > 0 时是"报价单"，费用称"服务费"。
    let quote = inv.markup > 0.0;
    let title = if quote {
        "AI 用量报价单"
    } else {
        "AI 用量账单"
    };
    let total_suffix = if quote {
        format!("（含服务费 {:.0}% · 估算未含税）", inv.markup * 100.0)
    } else {
        "（估算未含税）".to_string()
    };
    format!(
        "<!doctype html><html><head><meta charset=utf-8><title>Invoice {client}</title>\
    <style>*{{box-sizing:border-box;margin:0}}@page{{size:A4;margin:18mm}}body{{font:14px/1.6 'Segoe UI',system-ui,sans-serif;color:#111;{wm}}}\
    h1{{font-size:22px;margin:0 0 4px}}.muted{{color:#666;font-size:12px}}\
    table{{width:100%;border-collapse:collapse;margin-top:18px;font-size:12px}}\
    th,td{{text-align:left;padding:5px 5px;border-bottom:1px solid #ddd}}th{{font-size:11px;color:#555;background:#fafafa}}\
    .n{{text-align:right;font-variant-numeric:tabular-nums}}.note{{color:#999;font-size:10px;margin-top:2px}}.total{{margin-top:18px;text-align:right;font-size:18px}}\
    .meta{{margin-top:26px;font-size:11px;color:#888;border-top:1px solid #eee;padding-top:8px}}</style></head>\
    <body><h1>{title} · {client}</h1>\
    <div class=muted>编号 {no} · 周期 {from} ~ {to} · 币种 {currency} · 生成于 {gen}</div>\
    <table><thead><tr><th>工具</th><th>科目</th><th>计价单位</th><th>价档</th><th class=n>数量</th><th class=n>单价</th><th class=n>金额</th></tr></thead>\
    <tbody>{rows}</tbody></table>\
    <div class=total>合计：{sym}{total:.2} {currency}{total_suffix}</div>\
    <div class=meta>口径：token×厂商公开定价页单价 + 工具按次计费；高峰/空闲按事件时间分档，按次价不随时段折扣；单价单位：token 每百万、按次每千次。估算未含税；金额以厂商账单为准，本单提供归因分项。\
    账本指纹 {basis} · 费率表指纹 {rates_fp} · eBouncer v{ver}{watermark_note}</div></body></html>",
        client = esc(&inv.client),
        title = title,
        no = esc(&no),
        from = esc(&fmt_date(&inv.period.from)),
        to = esc(&fmt_date(&inv.period.to)),
        currency = esc(&inv.currency),
        gen = esc(&fmt_datetime(&inv.generated_at)),
        sym = sym,
        wm = wm,
        rows = rows,
        total = inv.total,
        total_suffix = total_suffix,
        basis = esc(inv.data_basis.as_deref().unwrap_or("-")),
        rates_fp = esc(&inv.rates_fingerprint[..inv.rates_fingerprint.len().min(12)]),
        ver = crate::VERSION,
        watermark_note = if inv.watermark { " · 演示水印" } else { "" },
    )
}

/// 找本机无头浏览器：EBC_BROWSER 环境变量优先，其次 Edge/Chrome 常见路径。
pub fn find_browser() -> Option<PathBuf> {
    if let Ok(p) = std::env::var("EBC_BROWSER") {
        let p = PathBuf::from(p);
        if p.exists() {
            return Some(p);
        }
    }
    let candidates: Vec<PathBuf> = if cfg!(windows) {
        [
            "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
            "C:/Program Files/Microsoft/Edge/Application/msedge.exe",
            "C:/Program Files/Google/Chrome/Application/chrome.exe",
            "C:/Program Files (x86)/Google/Chrome/Application/chrome.exe",
        ]
        .iter()
        .map(PathBuf::from)
        .collect()
    } else {
        [
            "google-chrome",
            "chromium",
            "chromium-browser",
            "microsoft-edge",
        ]
        .iter()
        .map(|n| PathBuf::from(format!("/usr/bin/{n}")))
        .chain(
            std::env::var("PATH")
                .unwrap_or_default()
                .split(std::path::MAIN_SEPARATOR)
                .map(|d| PathBuf::from(d).join("google-chrome")),
        )
        .collect()
    };
    candidates.into_iter().find(|p| p.exists())
}

/// 路径 → file:// URL。
/// 真机事故根因：Windows 下 canonicalize() 返回 `\\?\C:\...` verbatim 前缀，直接拼进 file://
/// 得到 `file:////?/C:/...` 非法 URL → 浏览器打不开 → 回退打印自己的新标签页（灰块+隐私弹窗）。
/// 故必须剥离 verbatim 前缀，并对空格/中文做百分号编码。
fn file_url(path: &Path) -> String {
    let abs = path.canonicalize().unwrap_or_else(|_| path.to_path_buf());
    let mut s = abs.display().to_string();
    if let Some(rest) = s.strip_prefix(r"\\?\") {
        s = rest.to_string();
    } else if let Some(rest) = s.strip_prefix(r"\\.\") {
        s = rest.to_string();
    }
    s = s.replace('\\', "/");
    let encoded = percent_encode(&s);
    if encoded.starts_with('/') {
        format!("file://{encoded}")
    } else {
        format!("file:///{encoded}")
    }
}

/// 保守百分号编码：仅保留 URL 安全字符，其余按 UTF-8 字节转 %XX。
fn percent_encode(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for b in s.as_bytes() {
        match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'/' | b':' | b'-' | b'_' | b'.' => {
                out.push(*b as char)
            }
            _ => out.push_str(&format!("%{b:02X}")),
        }
    }
    out
}

/// PDF 有效性：存在、非空壳、以 %PDF 头开始。
fn pdf_ok(p: &Path) -> bool {
    std::fs::read(p)
        .map(|b| b.len() > 1024 && b.starts_with(b"%PDF"))
        .unwrap_or(false)
}

/// HTML → PDF。浏览器缺失时返回 Err 并保留 HTML 作为降级交付物。
pub fn html_to_pdf(html_path: &Path, pdf_path: &Path) -> Result<(), String> {
    let browser = find_browser().ok_or_else(|| {
        "未找到 Chrome/Edge（可设 EBC_BROWSER 指向浏览器路径；HTML 版可直接使用）".to_string()
    })?;
    // 独立临时 profile：否则 headless Edge 读用户真实配置，弹出"微软重视您的隐私"首启页
    // 并被一起打印进 PDF（真机事故根因之二）。
    let tmp_profile = std::env::temp_dir().join(format!("ebc-pdf-{}", std::process::id()));
    let _ = std::fs::create_dir_all(&tmp_profile);
    let run = |flag: &str| {
        Command::new(&browser)
            .args([
                flag,
                "--disable-gpu",
                "--no-first-run",
                "--no-default-browser-check",
                "--disable-extensions",
                &format!("--user-data-dir={}", tmp_profile.display()),
                "--no-pdf-header-footer",
                &format!("--print-to-pdf={}", pdf_path.display()),
                "--virtual-time-budget=8000",
                &file_url(html_path),
            ])
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
    };
    let mut st = run("--headless=new").map_err(|e| format!("启动浏览器失败：{e}"))?;
    if !st.success() || !pdf_ok(pdf_path) {
        // 旧版内核不认识 --headless=new，回退 --headless
        st = run("--headless").map_err(|e| format!("启动浏览器失败：{e}"))?;
    }
    let _ = std::fs::remove_dir_all(&tmp_profile);
    if st.success() && pdf_ok(pdf_path) {
        Ok(())
    } else {
        let _ = std::fs::remove_file(pdf_path); // 清掉空壳/错误页，避免误交
        Err("浏览器渲染失败，已保留 HTML".to_string())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    fn inv(watermark: bool) -> Invoice {
        Invoice {
            client: "ACME".into(),
            period: crate::bill::Period {
                from: "2026-11-01".into(),
                to: "2026-11-02".into(),
            },
            items: vec![crate::bill::BillItem {
                tool: "dsh".into(),
                category: "token_input".into(),
                qty: 1000000,
                unit_price_per_k_or_mtok: 2.0,
                amount: 2.0,
                price_source: "费率表 deepseek@2026-11-01 · 高峰价".into(),
                note: None,
            }],
            markup: 0.2,
            total: 2.4,
            currency: "CNY".into(),
            generated_at: "2026-11-02T00:00:00Z".into(),
            data_basis: Some("abcd1234".into()),
            rates_snapshot: vec![],
            rates_fingerprint: "feedface".into(),
            watermark,
        }
    }
    #[test]
    fn html_has_watermark_when_free() {
        let h = invoice_html(&inv(true));
        assert!(h.contains("Generated by eBouncer"));
        assert!(h.contains("ACME"));
        assert!(h.contains("2.40"));
        assert!(h.contains("费率表指纹 feedface"), "{h}");
    }

    #[test]
    fn html_shows_unit_tier_and_invoice_number() {
        let mut i = inv(false);
        i.items.push(crate::bill::BillItem {
            tool: "dsh".into(),
            category: "search_request".into(),
            qty: 12,
            unit_price_per_k_or_mtok: 5.0,
            amount: 0.06,
            price_source: "费率表 deepseek@2026-11-01 · 按次价（无时段折扣）".into(),
            note: Some("按次计费自 2026-11-01 起，本周期只记量不计费".into()),
        });
        let h = invoice_html(&i);
        assert!(h.contains("1M tokens"), "{h}");
        assert!(h.contains("1K 次"), "{h}");
        assert!(h.contains("高峰"), "{h}");
        assert!(h.contains("按次"), "{h}");
        assert!(h.contains("INV-20261102-ABCD1234"), "{h}");
        assert!(h.contains("¥2.0000"), "{h}");
        assert!(
            h.contains("<div class=note>按次计费自 2026-11-01 起"),
            "{h}"
        );
    }

    #[test]
    fn cost_invoice_has_no_service_fee_wording() {
        let mut i = inv(false);
        i.markup = 0.0;
        i.total = 2.0;
        let h = invoice_html(&i);
        assert!(h.contains("AI 用量账单"), "{h}");
        assert!(!h.contains("服务费"), "{h}");
        assert!(!h.contains("加成"), "{h}");
        assert!(!h.contains("报价单"), "{h}");
    }
    #[test]
    fn clean_invoice_has_no_watermark() {
        assert!(!invoice_html(&inv(false)).contains("Generated by eBouncer"));
    }
    #[test]
    fn html_escapes_injection() {
        let mut i = inv(false);
        i.client = "<script>alert(1)</script>".into();
        let h = invoice_html(&i);
        assert!(!h.contains("<script>alert"));
        assert!(h.contains("&lt;script&gt;"));
    }
    /// 回归（真机灰块事故）：水印曾是带 body{} 外壳的完整规则，插进 body 规则内部
    /// 形成非法嵌套 → Edge 错误恢复 → 整页只剩背景色。
    #[test]
    fn watermark_css_is_declaration_only_and_style_balanced() {
        let h = invoice_html(&inv(true));
        let style = h
            .split("<style>")
            .nth(1)
            .and_then(|s| s.split("</style>").next())
            .unwrap_or("");
        assert!(!style.contains("body{body"), "CSS 选择器嵌套非法");
        assert_eq!(
            style.matches('{').count(),
            style.matches('}').count(),
            "CSS 花括号不平衡"
        );
        assert!(style.contains("background-image:url("), "水印声明缺失");
    }
    /// 回归（真机"PDF 打的是 Edge 首启页"事故）：file_url 必须处理 Windows 路径。
    #[test]
    fn file_url_percent_encodes_spaces_and_nonascii() {
        // 空格与中文必须编码，冒号/斜杠保留
        let u = file_url(Path::new("/tmp/账 单/a.html"));
        assert!(u.starts_with("file:///tmp/"), "{u}");
        assert!(u.contains("%E8%B4%A6"), "中文未编码：{u}");
        assert!(u.contains("%20"), "空格未编码：{u}");
        assert!(!u.contains(' '), "URL 残留裸空格");
    }
    #[test]
    fn percent_encode_keeps_safe_chars() {
        assert_eq!(percent_encode("C:/a b/c-d_e.f"), "C:/a%20b/c-d_e.f");
    }
}
